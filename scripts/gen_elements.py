"""Generate src/minimol/static/js/elements.js from RDKit's periodic table.

Symbols and covalent radii come from RDKit, so the UI and the chemistry
backend agree on which elements exist. Colours are an aesthetic choice for
minimol (loosely following common CPK conventions), not reference data.

Run:  python scripts/gen_elements.py
"""

from pathlib import Path

from rdkit import Chem

COLORS = {
    "H": "#f2f2f2", "He": "#d9ffff", "Li": "#cc80ff", "Be": "#c2ff00", "B": "#ffb5b5",
    "C": "#8c8c8c", "N": "#3f5fe0", "O": "#e8312a", "F": "#8fd650", "Ne": "#b3e3f5",
    "Na": "#ab5cf2", "Mg": "#8aff00", "Al": "#bfa6a6", "Si": "#f0c8a0", "P": "#ff8c1a",
    "S": "#f2d231", "Cl": "#2fcf3a", "Ar": "#80d1e3", "K": "#8f40d4", "Ca": "#3dff00",
    "Ti": "#bfc2c7", "Cr": "#8a99c7", "Mn": "#9c7ac7", "Fe": "#e06633", "Co": "#f090a0",
    "Ni": "#50d050", "Cu": "#c88033", "Zn": "#7d80b0", "Br": "#a62929", "Ru": "#248f8f",
    "Rh": "#0a7d8c", "Pd": "#006985", "Ag": "#c0c0c0", "I": "#940094", "Pt": "#d0d0e0",
    "Au": "#ffd123", "Hg": "#b8b8d0", "Se": "#ffa100", "Sn": "#668080", "Xe": "#429eb0",
}
DEFAULT_COLOR = "#e07ad0"


def main() -> None:
    pt = Chem.GetPeriodicTable()
    rows = []
    for z in range(1, 119):
        sym = pt.GetElementSymbol(z)
        rcov = round(pt.GetRcovalent(z), 3)
        if rcov <= 0:
            rcov = 1.5
        rows.append(f'  ["{sym}", {rcov}, "{COLORS.get(sym, DEFAULT_COLOR)}"],')
    out = Path(__file__).resolve().parents[1] / "src/minimol/static/js/elements.js"
    out.write_text(
        "// Generated by scripts/gen_elements.py from RDKit's periodic table. Do not edit.\n"
        "// [symbol, covalent radius (Angstrom, RDKit), display colour]\n"
        "const TABLE = [\n" + "\n".join(rows) + "\n];\n\n"
        "export const SYMBOLS = TABLE.map((r) => r[0]);\n"
        "const INDEX = new Map(TABLE.map((r, i) => [r[0], i]));\n\n"
        "/** True if `sym` is an element symbol with exact capitalisation (\"Cl\", not \"CL\"). */\n"
        "export function isElement(sym) {\n  return INDEX.has(sym);\n}\n\n"
        "/** Normalise user input such as \"cl\" to \"Cl\"; returns null if it is not an element. */\n"
        "export function normalizeSymbol(text) {\n"
        "  const t = String(text).trim();\n"
        "  const sym = t.charAt(0).toUpperCase() + t.slice(1).toLowerCase();\n"
        "  return INDEX.has(sym) ? sym : null;\n}\n\n"
        "export function atomicNumber(sym) {\n  const i = INDEX.get(sym);\n  return i === undefined ? 0 : i + 1;\n}\n\n"
        "export function covalentRadius(sym) {\n  const i = INDEX.get(sym);\n  return i === undefined ? 1.5 : TABLE[i][1];\n}\n\n"
        "export function color(sym) {\n  const i = INDEX.get(sym);\n  return i === undefined ? \"" + DEFAULT_COLOR + "\" : TABLE[i][2];\n}\n\n"
        "/** Typical bond length used when placing a new atom (refined by optimization). */\n"
        "export function bondLength(a, b) {\n  return covalentRadius(a) + covalentRadius(b);\n}\n"
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
